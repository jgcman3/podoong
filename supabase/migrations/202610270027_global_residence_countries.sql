alter table public.families drop constraint family_residence_region_pair,
 add constraint family_residence_region_pair check(residence_region_code is null or residence_country_code is not null),
 add constraint family_residence_country_fk foreign key(residence_country_code) references public.residence_countries(code);

create function public.save_family_residence_country(p_family uuid,p_country_code text,p_version integer) returns void
language plpgsql security definer set search_path='' as $$
declare current_version integer;
begin
 if auth.uid() is null or not public.account_active() or not public.is_family_owner(p_family) then raise exception 'forbidden' using errcode='42501'; end if;
 select residence_version into current_version from public.families where id=p_family for update;
 if p_version is null or current_version is null or current_version<>p_version then raise exception 'conflict'; end if;
 if not exists(select 1 from public.residence_countries where code=p_country_code and enabled) then raise exception 'invalid country' using errcode='22023'; end if;
 update public.families set residence_country_code=p_country_code,residence_region_code=null,
 residence_city=null,residence_locality=null,residence_version=residence_version+1,residence_updated_at=now() where id=p_family;
 insert into public.audit_events(family_id,actor_id,action,subject_id) values(p_family,auth.uid(),'family_residence_saved',p_family);
end $$;
revoke all on function public.save_family_residence_country(uuid,text,integer) from public,anon;
grant execute on function public.save_family_residence_country(uuid,text,integer) to authenticated;

create or replace function public.community_board_locations()
 returns table(family_id uuid,country_code text,country_name text,scope text,region_code text,region_name text)
 language sql stable security definer set search_path='' as $$
 with recursive homes as (
  select f.id family_id,f.residence_country_code country_code,f.residence_region_code region_code,c.name country_name
  from public.family_members m join public.families f on f.id=m.family_id
  join public.residence_countries c on c.code=f.residence_country_code and c.enabled
  left join public.residence_regions r on r.country_code=c.code and r.code=f.residence_region_code and r.active and r.selectable
  where (f.residence_region_code is null or r.code is not null) and m.user_id=auth.uid() and public.community_participant() and public.account_active()
 ), path as (
  select h.family_id,h.country_code,r.code,r.parent_code,r.level,r.kind,r.community_scope,r.city_name,r.locality_name,r.active
  from homes h join public.residence_regions r on r.country_code=h.country_code and r.code=h.region_code
  union all
  select a.family_id,a.country_code,r.code,r.parent_code,r.level,r.kind,r.community_scope,r.city_name,r.locality_name,r.active
  from path a join public.residence_regions r on r.country_code=a.country_code and r.code=a.parent_code
 ), valid_homes as (
  select h.* from homes h where not exists(select 1 from path a where a.family_id=h.family_id and not a.active)
 ), regional as (
  select distinct on(a.family_id,a.community_scope) a.family_id,a.country_code,h.country_name,a.community_scope scope,a.code region_code,
   case when a.kind in ('province','district') then a.city_name else a.city_name||' '||a.locality_name end region_name
  from path a join valid_homes h on h.family_id=a.family_id where a.community_scope is not null
  order by a.family_id,a.community_scope,a.level desc
 ) select * from regional
 union all select h.family_id,h.country_code,h.country_name,'topic',null,null from valid_homes h;
$$;
