export function completedMonths(
  birth: string | null,
  today: string,
): number | null {
  if (!birth || birth > today) return null;
  const [y, m, d] = birth.split('-').map(Number),
    [ty, tm, td] = today.split('-').map(Number);
  const lastDay = new Date(Date.UTC(ty, tm, 0)).getUTCDate();
  return (ty - y) * 12 + tm - m - (td < Math.min(d, lastDay) ? 1 : 0);
}
export function developmentStage(month: number) {
  return (
    developmentStages.find((stage) => stage.month >= month) ??
    developmentStages[developmentStages.length - 1]
  );
}
export function sleepHours(month: number) {
  return month < 4
    ? '14–17'
    : month < 12
      ? '12–16'
      : month < 36
        ? '11–14'
        : '10–13';
}
